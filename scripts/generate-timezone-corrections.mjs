/**
 * Regenerates src/utils/timezone-corrections.ts: the zones whose rules in timezone-support's
 * bundled tz data differ from this Node's ICU tz data. Rerun when
 * test/timezone-corrections.spec.ts says the data has drifted, using a current Node.
 *
 *   npm run generate:tz-corrections
 */
import { writeFileSync } from "node:fs";
import {
	findTimeZone,
	getTimeZoneLinks,
	getUTCOffset,
	listTimeZones,
} from "timezone-support";

const FIRST_YEAR = 2026;
const LAST_YEAR = 2050;
const DAY_MS = 86_400_000;
const OUT = new URL("../src/utils/timezone-corrections.ts", import.meta.url);

const formatterFor = (name) =>
	new Intl.DateTimeFormat("en-US", {
		timeZone: name,
		timeZoneName: "longOffset",
	});

/** Minutes behind UTC, the sign timezone-support uses. */
const icuOffset = (formatter, instant) => {
	const label = formatter
		.formatToParts(instant)
		.find((part) => part.type === "timeZoneName").value;
	const match = label.match(/GMT([+-])(\d{2}):(\d{2})/);
	if (!match) return 0;
	const minutes = Number(match[2]) * 60 + Number(match[3]);
	return match[1] === "+" ? -minutes : minutes;
};

const icuAbbreviation = (name, instant) =>
	new Intl.DateTimeFormat("en-US", { timeZone: name, timeZoneName: "short" })
		.formatToParts(instant)
		.find((part) => part.type === "timeZoneName").value;

const bundledZone = (name) => {
	try {
		return findTimeZone(name);
	} catch {
		return null;
	}
};

const start = Date.UTC(FIRST_YEAR, 0, 1);
const end = Date.UTC(LAST_YEAR + 1, 0, 1);

const icuTransitions = (formatter) => {
	const transitions = [];
	for (let low = start; low < end; low += DAY_MS) {
		let high = low + DAY_MS;
		if (icuOffset(formatter, low) === icuOffset(formatter, high)) continue;
		let from = low;
		while (high - from > 1000) {
			const middle = Math.floor((from + high) / 2);
			if (icuOffset(formatter, middle) === icuOffset(formatter, from)) {
				from = middle;
			} else {
				high = middle;
			}
		}
		transitions.push(Math.round(high / 1000) * 1000);
	}
	return transitions;
};

const names = [
	...new Set([
		...Intl.supportedValuesOf("timeZone"),
		...listTimeZones(),
		...Object.keys(getTimeZoneLinks()),
	]),
].sort();

const corrections = {};
for (const name of names) {
	let formatter;
	try {
		formatter = formatterFor(name);
	} catch {
		continue; // A name only the bundled data knows; nothing to compare it with.
	}
	const bundled = bundledZone(name);
	let differs = !bundled;
	for (let at = start; !differs && at < end; at += DAY_MS) {
		differs = getUTCOffset(at, bundled).offset !== icuOffset(formatter, at);
	}
	if (!differs) continue;

	// Keep bundled history; only rules from FIRST_YEAR on are replaced.
	const keptCount = bundled
		? bundled.untils.filter((until) => until <= start).length
		: 0;
	const abbreviations = bundled
		? bundled.abbreviations.slice(0, keptCount)
		: [];
	const offsets = bundled ? bundled.offsets.slice(0, keptCount) : [];
	const untils = bundled ? bundled.untils.slice(0, keptCount) : [];

	// Each entry applies up to its `until`, so the first new entry covers from the last kept one.
	for (const until of [
		...icuTransitions(formatter),
		Number.POSITIVE_INFINITY,
	]) {
		const inside = Number.isFinite(until) ? until - 1000 : end;
		abbreviations.push(icuAbbreviation(name, inside));
		offsets.push(icuOffset(formatter, inside));
		untils.push(until);
	}
	corrections[name] = {
		name,
		abbreviations,
		offsets,
		untils,
		population: bundled?.population ?? 0,
	};
}

const body = Object.entries(corrections)
	.map(([name, zone]) => {
		const untils = zone.untils
			.map((until) => (Number.isFinite(until) ? String(until) : "Infinity"))
			.join(", ");
		return `\t${JSON.stringify(name)}: {
		name: ${JSON.stringify(zone.name)},
		abbreviations: ${JSON.stringify(zone.abbreviations)},
		offsets: ${JSON.stringify(zone.offsets)},
		untils: [${untils}],
		population: ${zone.population},
	},`;
	})
	.join("\n");

writeFileSync(
	OUT,
	`// Generated by scripts/generate-timezone-corrections.mjs. Do not edit by hand.
// tzdata ${process.versions.tz}, rules compared ${FIRST_YEAR}-${LAST_YEAR}.

export const TIME_ZONE_CORRECTIONS: Record<
	string,
	{
		name: string;
		abbreviations: string[];
		offsets: number[];
		untils: number[];
		population: number;
	}
> = {
${body}
};
`,
);
console.log(
	`tzdata ${process.versions.tz}: ${Object.keys(corrections).join(", ")}`,
);
